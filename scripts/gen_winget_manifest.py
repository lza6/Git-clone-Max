"""生成 winget 清单（G80-B7-4）：从**真实产物**读版本与 sha256，产出三份 YAML。

为什么要有脚本而不是手写：winget 清单里必须写 `PackageVersion` / `InstallerUrl` /
`InstallerSha256`，而这四样每次发版都变；手写必然漂移（本项目已经因为「secrets 写死」
「版本号硬编码」吃过两次教训）。脚本从 `dist/` 与 `gcm/__init__.py` **读真实值**，
生成后可交给 `wingetcreate`/PR 使用。

用法：
    python scripts/gen_winget_manifest.py --out packaging/winget
    python scripts/gen_winget_manifest.py --check      # 只校验现有清单与产物是否一致

边界：脚本**不联网、不提审**。提交到 winget-pkgs 仍是人工动作（需审批与署名的发布流程）。
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

PACKAGE_ID = "lza6.Git-clone-Max"
PUBLISHER = "lza6"
PACKAGE_NAME = "Git-clone-Max"
REPO_URL = "https://github.com/lza6/Git-clone-Max"
INSTALLER_URL_TMPL = REPO_URL + "/releases/download/v{ver}/Git-clone-Max.exe"


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def build_manifests(version: str, installer_url: str, sha256: str) -> dict[str, str]:
    """返回 {文件名: 内容}（三份 winget YAML）。纯函数，便于测试。"""
    ver = str(version).strip().lstrip("v")
    if not ver or ver.count(".") < 2:
        raise ValueError(f"版本号不合法：{version!r}")
    if len(sha256) != 64 or any(c not in "0123456789abcdef" for c in sha256.lower()):
        raise ValueError("sha256 必须是 64 位十六进制")
    version_yaml = (
        f"# Generated by scripts/gen_winget_manifest.py — do not edit by hand.\n"
        f"PackageIdentifier: {PACKAGE_ID}\n"
        f"PackageVersion: {ver}\n"
        f"DefaultLocale: zh-CN\n"
        f"ManifestType: version\n"
        f"ManifestVersion: 1.6.0\n"
    )
    locale_yaml = (
        f"# Generated by scripts/gen_winget_manifest.py — do not edit by hand.\n"
        f"PackageIdentifier: {PACKAGE_ID}\n"
        f"PackageVersion: {ver}\n"
        f"PackageLocale: zh-CN\n"
        f"Publisher: {PUBLISHER}\n"
        f"PackageName: {PACKAGE_NAME}\n"
        f"License: MIT\n"
        f"ShortDescription: GitHub/GitLab/Gitee 仓库批量并行克隆与增量更新（PyQt6 桌面工具）\n"
        f"PackageUrl: {REPO_URL}\n"
        f"ManifestType: defaultLocale\n"
        f"ManifestVersion: 1.6.0\n"
    )
    installer_yaml = (
        f"# Generated by scripts/gen_winget_manifest.py — do not edit by hand.\n"
        f"PackageIdentifier: {PACKAGE_ID}\n"
        f"PackageVersion: {ver}\n"
        f"InstallerLocale: zh-CN\n"
        f"InstallerType: portable\n"
        f"Commands:\n"
        f"  - Git-clone-Max\n"
        f"Installers:\n"
        f"  - Architecture: x64\n"
        f"    InstallerUrl: {installer_url}\n"
        f"    InstallerSha256: {sha256.lower()}\n"
        f"ManifestType: installer\n"
        f"ManifestVersion: 1.6.0\n"
    )
    return {
        f"{PACKAGE_ID}.yaml": version_yaml,
        f"{PACKAGE_ID}.locale.zh-CN.yaml": locale_yaml,
        f"{PACKAGE_ID}.installer.yaml": installer_yaml,
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="生成 winget 清单（从真实产物读版本与 sha256）")
    ap.add_argument("--out", default=str(ROOT / "packaging" / "winget"),
                    help="输出目录（默认 packaging/winget）")
    ap.add_argument("--exe", default=str(ROOT / "dist" / "Git-clone-Max.exe"),
                    help="安装包路径（默认 dist/Git-clone-Max.exe）")
    ap.add_argument("--check", action="store_true",
                    help="只校验：产物与清单里的版本/sha256 是否一致（不一致 → 退出码 1）")
    args = ap.parse_args(argv)

    from gcm import __version__

    exe = Path(args.exe)
    if not exe.is_file():
        print(f"[FAIL] 找不到产物：{exe}（先跑 PyInstaller）", file=sys.stderr)
        return 2
    sha = _sha256(exe)
    url = INSTALLER_URL_TMPL.format(ver=__version__)
    try:
        files = build_manifests(__version__, url, sha)
    except ValueError as e:
        print(f"[FAIL] {e}", file=sys.stderr)
        return 2

    out_dir = Path(args.out)
    if args.check:
        problems = []
        for name, content in files.items():
            target = out_dir / name
            if not target.is_file():
                problems.append(f"缺少 {name}")
            elif target.read_text(encoding="utf-8") != content:
                problems.append(f"{name} 与产物不一致（版本或 sha256 变了？）")
        if problems:
            print("[FAIL] " + "；".join(problems), file=sys.stderr)
            return 1
        print(f"[OK] winget 清单与产物一致（{__version__} · {sha[:12]}…）")
        return 0

    out_dir.mkdir(parents=True, exist_ok=True)
    for name, content in files.items():
        (out_dir / name).write_text(content, encoding="utf-8", newline="\n")
    print(f"[OK] 已生成 3 份清单到 {out_dir}（版本 {__version__} · sha256 {sha[:12]}…）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
